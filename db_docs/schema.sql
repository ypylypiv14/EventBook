-- EventBook Database Schema

DROP DATABASE IF EXISTS eventbook_db;
CREATE DATABASE eventbook_db;
USE eventbook_db;

-- Table: USER

CREATE TABLE IF NOT EXISTS USER (
    userID INT AUTO_INCREMENT PRIMARY KEY,
    firstName VARCHAR(100) NOT NULL,
    lastName VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    phone INT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'CLIENT',
    timeCreated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Table: VENUE_SPACE

CREATE TABLE IF NOT EXISTS VENUE (
    venueID INT AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    capacity INT NOT NULL,
    locationType VARCHAR(100) NULL
);

-- Table: EVENT

CREATE TABLE IF NOT EXISTS EVENT (
    eventID INT AUTO_INCREMENT PRIMARY KEY,
    userID INT NOT NULL,
    name VARCHAR(150) NOT NULL,
    eventType VARCHAR(50) NOT NULL,
    guestCount INT NOT NULL,
    notes TEXT NULL,
    createdAT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT userFK FOREIGN KEY (userID) REFERENCES USER(userID) 
);

-- Table: RESERVATION

CREATE TABLE IF NOT EXISTS RESERVATION (
    reservationD INT AUTO_INCREMENT PRIMARY KEY,
    eventID INT NOT NULL,
    venueID INT NOT NULL,
    coordinatorID INT NULL,
    startTime DATETIME NOT NULL,
    endTime DATETIME NOT NULL,
    CONSTRAINT eventFK FOREIGN KEY (eventID) REFERENCES EVENT(eventID),
    CONSTRAINT venueFK FOREIGN KEY (venueID) REFERENCES VENUE(venueID),
    CONSTRAINT coordinatorFK FOREIGN KEY (coordinatorID) REFERENCES USER(userID)
);